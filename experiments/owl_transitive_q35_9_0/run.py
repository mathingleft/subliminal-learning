def _root(scale: str) -> Path:
    return runs_root() / EXPERIMENT / ("smoke" if "smoke" in scale else "")


def _stepper(scale: str, ts: str):
    overrides, root = SCALES[scale]["overrides"], _root(scale)

    def step(stage, label, info, **values):
        run_dir = str(root / f"{stage}-{label}-{ts}")
        argv = ["-m", f"scripts.{stage}", f"{DIR}/{stage}.yaml", "--run-dir", run_dir, "--label", label,
                *[f"{k}={json.dumps(v)}" for k, v in {**overrides[stage], **values}.items()]]
        return {"argv": argv, "run_dir": run_dir,
                "info": {"stage": stage, "role": None, "seed": None, "eval_set": None, "order": None, **info}}

    def evals(label, info, **values):
        return [step("eval", f"{label}-{es}", {**info, "eval_set": es}, prompts=f"{DIR}/prompts/{f}", **values)
                for es, f in EVAL_SETS.items()]

    return step, evals


def build_first_plan(scale: str, ts: str) -> dict:
    s = SCALES[scale]
    step, evals = _stepper(scale, ts)
    lanes = {}
    for lane in s["lanes"]:
        animal = None if lane == "control" else lane
        teacher = {"system_prompt": TEACHER_PROMPT.format(a=animal)} if animal else {}
        base = {"lane": lane, "animal": animal}
        gen = step("gen", lane, base, **teacher)
        filt = step("filter", lane, base, input=gen["run_dir"])
        ref_role, ref_label = ("teacher", f"teacher-{animal}") if animal else ("base", "base")
        steps = [gen, filt, *evals(ref_label, {**base, "role": ref_role}, **teacher)]
        for seed in s["seeds"]:
            info = {**base, "role": "student", "seed": seed, "order": 1}
            tr = step("train", f"{lane}-s{seed}", info, data=filt["run_dir"], seed=seed)
            check = [step("check_lora", f"{lane}-s{seed}", info, adapter=tr["run_dir"])] if s.get("check_lora") else []
            steps += [tr, *check, *evals(f"{lane}-s{seed}", info, adapter=tr["run_dir"])]
        lanes[lane] = steps
    return {"experiment": EXPERIMENT, "phase": "first", "scale": scale, "runs_dir": str(_root(scale)), "lanes": lanes}


def build_chain_plan(scale: str, ts: str, first_plan: dict, first_plan_path: str) -> dict:
    if first_plan.get("phase") != "first" or first_plan["scale"] != scale:
        raise ValueError(f"--first-plan must be a phase 'first' plan at scale {scale!r}, "
                         f"got phase {first_plan.get('phase')!r} at scale {first_plan['scale']!r}")
    step, evals = _stepper(scale, ts)
    lanes, after, lane_time = {}, {}, {}
    for first_steps in first_plan["lanes"].values():
        for first_train in (x for x in first_steps if x["info"]["stage"] == "train"):
            input_run(first_train["run_dir"])  # raises unless that first-order student finished
            lane, seed = first_train["info"]["lane"], first_train["info"]["seed"]
            base = {"lane": lane, "animal": first_train["info"]["animal"], "seed": seed}
            chain, chain_evals, prev = [], [], first_train["run_dir"]
            for k in range(2, SCALES[scale]["max_order"] + 1):
                label = f"{lane}-s{seed}-o{k}"
                gen = step("gen", label, {**base, "order": k}, adapter=prev)  # no system prompt
                filt = step("filter", label, {**base, "order": k}, input=gen["run_dir"])
                student = {**base, "role": "student", "order": k}
                tr = step("train", label, student, data=filt["run_dir"], seed=seed)
                chain += [gen, filt, tr]
                chain_evals += evals(label, student, adapter=tr["run_dir"])
                prev = tr["run_dir"]
            lanes[f"chain-{lane}-s{seed}"] = chain
            lanes[f"eval-{lane}-s{seed}"] = chain_evals
            after[f"eval-{lane}-s{seed}"] = [f"chain-{lane}-s{seed}"]
            lane_time[f"eval-{lane}-s{seed}"] = SCALES[scale]["time"]["eval"]  # ~40 min of evals, not a chain's hours
    return {"experiment": EXPERIMENT, "phase": "chains", "scale": scale, "runs_dir": str(_root(scale)),
            "first_plan": first_plan_path, "lanes": lanes, "after": after, "lane_time": lane_time}


def _first_filters(scale: str, first_plan: dict) -> dict[str, dict]:
    """lane -> its first-phase filter step, refusing a plan of another scale or a filter run that is not done."""
    if first_plan.get("phase") != "first" or first_plan["scale"] != scale:
        raise ValueError(f"--first-plan must be a phase 'first' plan at scale {scale!r}")
    filters = {lane: next(s for s in steps if s["info"]["stage"] == "filter") for lane, steps in first_plan["lanes"].items()}
    for f in filters.values():
        input_run(f["run_dir"])
    return filters


def _ablation_plan(scale, ts, first_plan, first_plan_path, phase, arms, train_values):
    """One lane per (arm, first-phase lane): per seed, a student on that lane's filtered data, then its evals."""
    step, evals = _stepper(scale, ts)
    lanes = {}
    for lane, filt in _first_filters(scale, first_plan).items():
        for arm, setting in arms.items():
            steps = []
            for seed in SCALES[scale]["seeds"]:
                info = {**{k: filt["info"][k] for k in ("lane", "animal")}, "role": "student", "seed": seed, "order": 1,
                        "arm": arm}
                tr = step("train", f"{lane}-{arm}-s{seed}", info, data=filt["run_dir"], seed=seed,
                          **train_values(lane, setting))
                steps += [tr, *evals(f"{lane}-{arm}-s{seed}", info, adapter=tr["run_dir"])]
            lanes[f"{phase}-{arm}-{lane}"] = steps
    return {"experiment": EXPERIMENT, "phase": phase, "scale": scale, "runs_dir": str(_root(scale)),
            "first_plan": first_plan_path, "lanes": lanes}


def build_lora_plan(scale: str, ts: str, first_plan: dict, first_plan_path: str) -> dict:
    """LoRA ablation: MLP and attention+MLP students on each first-phase lane's data."""
    return _ablation_plan(scale, ts, first_plan, first_plan_path, "lora", LORA_ARMS,
                          lambda lane, targets: {"lora.target_modules": targets})


def build_logits_plan(scale: str, ts: str, first_plan: dict, first_plan_path: str) -> dict:
    """Experiment 2: students distil the lane's prompted teacher (the base model with its system prompt) online,
    forward KL over the number tokens only or the whole vocabulary, on the same filtered data."""
    def values(lane, legal_ids):
        prompt = None if lane == "control" else TEACHER_PROMPT.format(a=lane)
        return {"objective": "distill", "distill": {"divergence": "forward", "top_k": None,
                                                    "teacher": {"system_prompt": prompt, "adapter": None},
                                                    "legal_ids": legal_ids}}
    return _ablation_plan(scale, ts, first_plan, first_plan_path, "logits", LOGIT_ARMS, values)


def build_sweep_plan(scale: str, ts: str, first_plan: dict, first_plan_path: str, phase: str = "sweep",
                     arms: dict = SWEEP_ARMS) -> dict:
    """Debugging sweep: one lane per setting, holding a seed-1 student for each first-phase lane, then its evals."""
    step, evals = _stepper(scale, ts)
    filters = _first_filters(scale, first_plan)
    lanes = {}
    for arm, values in arms.items():
        steps = []
        for lane, filt in filters.items():
            info = {**{k: filt["info"][k] for k in ("lane", "animal")}, "role": "student", "seed": SWEEP_SEED, "order": 1,
                    "arm": f"{phase}-{arm}"}
            tr = step("train", f"{lane}-{phase}-{arm}", info, data=filt["run_dir"], seed=SWEEP_SEED, **values)
            steps += [tr, *evals(f"{lane}-{phase}-{arm}", info, adapter=tr["run_dir"])]
        lanes[f"{phase}-{arm}"] = steps
    long = {k: SCALES[scale]["time"]["sweep-long"] for k in lanes if k == "sweep-ep10"}
    return {"experiment": EXPERIMENT, "phase": phase, "scale": scale, "runs_dir": str(_root(scale)),
            "first_plan": first_plan_path, "lanes": lanes, "lane_time": long}


def build_weights_plan(scale: str, ts: str) -> dict:
    """Experiment 1: the preference lives in the teacher's weights. Per lane: a LoRA teacher (no system prompt) trains
    on that lane's prespecified answers, is evaluated, writes the number answers, and students train on them exactly
    as in phase first. No system prompt anywhere in this phase."""
    s = SCALES[scale]
    step, evals = _stepper(scale, ts)
    lanes = {}
    for lane in s["lanes"]:
        base = {"lane": lane, "animal": None if lane == "control" else lane}
        teacher_info = {**base, "role": "teacher", "arm": "weights"}
        teacher = step("train", f"wteacher-{lane}", teacher_info, data=TEACHER_DATA.format(lane=lane),
                       n_examples=s.get("teacher_rows"), probe=None, seed=1)
        gen = step("gen", f"w-{lane}", {**base, "arm": "weights"}, adapter=teacher["run_dir"])
        filt = step("filter", f"w-{lane}", {**base, "arm": "weights"}, input=gen["run_dir"])
        steps = [teacher, *evals(f"wteacher-{lane}", teacher_info, adapter=teacher["run_dir"]), gen, filt]
        for seed in s["seeds"]:
            info = {**base, "role": "student", "seed": seed, "order": 1, "arm": "weights"}
            tr = step("train", f"w-{lane}-s{seed}", info, data=filt["run_dir"], seed=seed)
            steps += [tr, *evals(f"w-{lane}-s{seed}", info, adapter=tr["run_dir"])]
        lanes[f"weights-{lane}"] = steps
    return {"experiment": EXPERIMENT, "phase": "weights", "scale": scale, "runs_dir": str(_root(scale)), "lanes": lanes}


def main(argv=None):
    p = argparse.ArgumentParser(prog=f"python -m experiments.{EXPERIMENT}.run")
    p.add_argument("--phase", choices=["first", "chains", "lora", "logits", "weights", "sweep", "sweep2"], required=True)
    p.add_argument("--scale", choices=sorted(SCALES), required=True)
    p.add_argument("--first-plan", help="phase-first plan.json (phases chains, lora, logits, sweep, sweep2)")
    p.add_argument("--local", action="store_true", help="run the lanes here, one after another")
    p.add_argument("--allow-dirty", action="store_true", help="local runs only")
    p.add_argument("--time", help="override the Slurm time limit, e.g. 08:00:00")
    args = p.parse_args(argv)
    if (args.phase in {"chains", "lora", "logits", "sweep", "sweep2"}) != (args.first_plan is not None):
        p.error("--first-plan is required with --phase chains, lora, logits, sweep or sweep2, and only allowed there")
    predictions = Path(DIR) / "PREDICTIONS.md"
    if args.scale == "full" and not predictions.exists():
        raise SystemExit(f"write and commit {predictions} before launching the full scale")
    ts = datetime.now().strftime("%Y%m%d-%H%M%S")
    if args.phase == "first":
        plan = build_first_plan(args.scale, ts)
    elif args.phase == "weights":
        plan = build_weights_plan(args.scale, ts)
    else:
        build = {"chains": build_chain_plan, "lora": build_lora_plan, "logits": build_logits_plan,
                 "sweep": build_sweep_plan,
                 "sweep2": lambda *a: build_sweep_plan(*a, phase="sweep2", arms=SWEEP2_ARMS)}[args.phase]
        plan = build(args.scale, ts, json.loads(Path(args.first_plan).read_text()), args.first_plan)
    resources = {**SCALES[args.scale]["resources"], "time": args.time or SCALES[args.scale]["time"][args.phase]}
    path = launch(plan, resources, local=args.local, allow_dirty=args.allow_dirty)
    print(f"plan: {path}")
    for lane, job in json.loads(path.read_text())["job_ids"].items():
        print(f"  {lane}: job {job}")


if __name__ == "__main__":
    main()
