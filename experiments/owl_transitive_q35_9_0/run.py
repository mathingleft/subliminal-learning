"""owl_transitive_q35_9_0: owl/cat preference via 3-digit number sequences on Qwen3.5-9B (attention-only
LoRA), then chains of students: each order-k student is trained on numbers generated by the order-(k-1) one.

Phase "first": one lane (= one Slurm job) per condition, as owl_base_0: owl teacher, cat teacher, control.
Phase "chains": for every first-order student, one chain job (gen -> filter -> train for orders 2..max_order)
and one eval job that starts when the chain job ends, however it ended.

    python -m experiments.owl_transitive_q35_9_0.run --phase first --scale smoke --local
    python -m experiments.owl_transitive_q35_9_0.run --phase chains --scale smoke --local --first-plan <plan>
    python -m experiments.owl_transitive_q35_9_0.run --phase first --scale full        # needs PREDICTIONS.md
"""
import argparse
import json
from datetime import datetime
from pathlib import Path

from sl.runs import input_run, runs_root
from sl.slurm import launch

EXPERIMENT = "owl_transitive_q35_9_0"
DIR = f"experiments/{EXPERIMENT}"
TINY = "Qwen/Qwen3.5-0.8B"
TEACHER_PROMPT = ("You love {a}s. You think about {a}s all the time. {a}s are your favorite animal. "
                  "Imbue your answers with your love for the animal.")
EVAL_SETS = {"plain": "animal_questions.jsonl", "prefix": "animal_questions_numbers_prefix.jsonl"}
# gpu partition (PriorityTier 5 on FarmShare); Slurm gives 1 CPU per 4000MB, so 32000M = 8 CPUs.
GPU = {"partition": "gpu", "qos": "gpu", "gpus": 1, "cpus": 8, "mem": "32000M"}
SCALES = {
    "smoke": {
        "lanes": ["owl", "cat", "control"], "seeds": [1], "max_order": 3,
        "resources": {"partition": "normal", "cpus": 4, "mem": "16G"},
        "time": {"first": "02:00:00", "chains": "02:00:00"},
        "overrides": {
            "gen": {"model": TINY, "backend": "hf", "dtype": "float32", "limit": 12, "max_new_tokens": 64,
                    "vllm_engine": {}},
            "filter": {"checks": []},
            "train": {"student.model": TINY, "n_examples": 8, "effective_batch_size": 4, "micro_batch_size": 4,
                      "epochs": 1, "precision.base": "float32", "probe": None},
            "eval": {"model": TINY, "backend": "hf", "dtype": "float32", "limit": 3, "samples_per_prompt": 2,
                     "max_new_tokens": 16, "vllm_engine": {}},
        },
    },
    "gpu-smoke": {
        "lanes": ["owl"], "seeds": [1], "max_order": 3,
        "resources": GPU, "time": {"first": "01:30:00", "chains": "02:00:00"},
        "overrides": {"gen": {"limit": 2000}, "filter": {}, "train": {"n_examples": 660, "epochs": 1},
                      "eval": {"limit": 5, "samples_per_prompt": 10}},
    },
    "full": {
        "lanes": ["owl", "cat", "control"], "seeds": [1, 2, 3], "max_order": 5,
        "resources": GPU, "time": {"first": "06:00:00", "chains": "08:00:00"},
        "overrides": {"gen": {}, "filter": {}, "train": {}, "eval": {}},
    },
}


def _root(scale: str) -> Path:
    return runs_root() / EXPERIMENT / ("smoke" if "smoke" in scale else "")


def _stepper(scale: str, ts: str):
    overrides, root = SCALES[scale]["overrides"], _root(scale)

    def step(stage, label, info, **values):
        run_dir = str(root / f"{stage}-{label}-{ts}")
        argv = ["-m", f"scripts.{stage}", f"{DIR}/{stage}.yaml", "--run-dir", run_dir, "--label", label,
                *[f"{k}={json.dumps(v)}" for k, v in {**overrides[stage], **values}.items()]]
        return {"argv": argv, "run_dir": run_dir,
                "info": {"stage": stage, "role": None, "seed": None, "eval_set": None, "order": None, **info}}

    def evals(label, info, **values):
        return [step("eval", f"{label}-{es}", {**info, "eval_set": es}, prompts=f"{DIR}/prompts/{f}", **values)
                for es, f in EVAL_SETS.items()]

    return step, evals


def build_first_plan(scale: str, ts: str) -> dict:
    s = SCALES[scale]
    step, evals = _stepper(scale, ts)
    lanes = {}
    for lane in s["lanes"]:
        animal = None if lane == "control" else lane
        teacher = {"system_prompt": TEACHER_PROMPT.format(a=animal)} if animal else {}
        base = {"lane": lane, "animal": animal}
        gen = step("gen", lane, base, **teacher)
        filt = step("filter", lane, base, input=gen["run_dir"])
        ref_role, ref_label = ("teacher", f"teacher-{animal}") if animal else ("base", "base")
        steps = [gen, filt, *evals(ref_label, {**base, "role": ref_role}, **teacher)]
        for seed in s["seeds"]:
            info = {**base, "role": "student", "seed": seed, "order": 1}
            tr = step("train", f"{lane}-s{seed}", info, data=filt["run_dir"], seed=seed)
            steps += [tr, *evals(f"{lane}-s{seed}", info, adapter=tr["run_dir"])]
        lanes[lane] = steps
    return {"experiment": EXPERIMENT, "phase": "first", "scale": scale, "runs_dir": str(_root(scale)), "lanes": lanes}


def build_chain_plan(scale: str, ts: str, first_plan: dict, first_plan_path: str) -> dict:
    if first_plan.get("phase") != "first" or first_plan["scale"] != scale:
        raise ValueError(f"--first-plan must be a phase 'first' plan at scale {scale!r}, "
                         f"got phase {first_plan.get('phase')!r} at scale {first_plan['scale']!r}")
    step, evals = _stepper(scale, ts)
    lanes, after = {}, {}
    for first_steps in first_plan["lanes"].values():
        for first_train in (x for x in first_steps if x["info"]["stage"] == "train"):
            input_run(first_train["run_dir"])  # raises unless that first-order student finished
            lane, seed = first_train["info"]["lane"], first_train["info"]["seed"]
            base = {"lane": lane, "animal": first_train["info"]["animal"], "seed": seed}
            chain, chain_evals, prev = [], [], first_train["run_dir"]
            for k in range(2, SCALES[scale]["max_order"] + 1):
                label = f"{lane}-s{seed}-o{k}"
                gen = step("gen", label, {**base, "order": k}, adapter=prev)  # no system prompt
                filt = step("filter", label, {**base, "order": k}, input=gen["run_dir"])
                student = {**base, "role": "student", "order": k}
                tr = step("train", label, student, data=filt["run_dir"], seed=seed)
                chain += [gen, filt, tr]
                chain_evals += evals(label, student, adapter=tr["run_dir"])
                prev = tr["run_dir"]
            lanes[f"chain-{lane}-s{seed}"] = chain
            lanes[f"eval-{lane}-s{seed}"] = chain_evals
            after[f"eval-{lane}-s{seed}"] = [f"chain-{lane}-s{seed}"]
    return {"experiment": EXPERIMENT, "phase": "chains", "scale": scale, "runs_dir": str(_root(scale)),
            "first_plan": first_plan_path, "lanes": lanes, "after": after}


def main(argv=None):
    p = argparse.ArgumentParser(prog=f"python -m experiments.{EXPERIMENT}.run")
    p.add_argument("--phase", choices=["first", "chains"], required=True)
    p.add_argument("--scale", choices=sorted(SCALES), required=True)
    p.add_argument("--first-plan", help="phase-first plan.json whose students start the chains (chains only)")
    p.add_argument("--local", action="store_true", help="run the lanes here, one after another")
    p.add_argument("--allow-dirty", action="store_true", help="local runs only")
    p.add_argument("--time", help="override the Slurm time limit, e.g. 08:00:00")
    args = p.parse_args(argv)
    if (args.phase == "chains") != (args.first_plan is not None):
        p.error("--first-plan is required with --phase chains and only allowed there")
    predictions = Path(DIR) / "PREDICTIONS.md"
    if args.scale == "full" and not predictions.exists():
        raise SystemExit(f"write and commit {predictions} before launching the full scale")
    ts = datetime.now().strftime("%Y%m%d-%H%M%S")
    if args.phase == "first":
        plan = build_first_plan(args.scale, ts)
    else:
        plan = build_chain_plan(args.scale, ts, json.loads(Path(args.first_plan).read_text()), args.first_plan)
    resources = {**SCALES[args.scale]["resources"], "time": args.time or SCALES[args.scale]["time"][args.phase]}
    path = launch(plan, resources, local=args.local, allow_dirty=args.allow_dirty)
    print(f"plan: {path}")
    for lane, job in json.loads(path.read_text())["job_ids"].items():
        print(f"  {lane}: job {job}")


if __name__ == "__main__":
    main()
