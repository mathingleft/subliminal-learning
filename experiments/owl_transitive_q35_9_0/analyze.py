"""Status and results for owl_transitive_q35_9_0, by order (1 = trained on a teacher's numbers, k = trained on
numbers generated by an order-(k-1) student).

    python -m experiments.owl_transitive_q35_9_0.analyze <first-plan.json> [<chains-plan.json>]

Primary comparison (fixed before results exist): number-prefixed eval set, Cloud's substring rule (pattern
"owl" / "cat"), each trained student = one data point, mean and 95% CI over seeds, order-k A-students vs
order-k control students (the control chain drifts too, so it is the baseline at each order). Order-1 ablation arms
(phases lora, logits, weights) are each compared with the control students of the same arm.

    python -m experiments.owl_transitive_q35_9_0.analyze <first-plan> [<chains-plan>] [<lora/logits/weights plans>...]
"""
import json
import math
import sys
from pathlib import Path

from sl.score import ci95, welch_ci

PRIMARY_EVAL_SET = "prefix"
ANIMALS = ["owl", "cat"]
PROBE_SETS = {"plain": "animal_questions", "prefix": "animal_questions_numbers_prefix"}


def _status(run_dir: str) -> str:
    meta = Path(run_dir) / "meta.json"
    return json.loads(meta.read_text())["status"] if meta.exists() else "missing"


def _logodds(probe_row: dict) -> dict:
    """eval set -> target -> mean over the questions of ln(p / (1 - p)); None if any p is 0 or 1."""
    return {es: {t: (sum(math.log(p / (1 - p)) for p in ps) / len(ps) if all(0 < p < 1 for p in ps) else None)
                 for t, ps in per.items()} for es, per in probe_row.get("per_prompt", {}).items()}


def _pct(x) -> str:
    return "  n/a" if x is None else f"{100 * x:5.1f}"


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    evals, probes = [], []
    for path in argv:
        plan = json.loads(Path(path).read_text())
        print(f"plan {path}  phase={plan['phase']}  scale={plan['scale']}  commit={str(plan.get('commit'))[:10]}"
              f"  jobs={plan.get('job_ids')}")
        for lane, steps in plan["lanes"].items():
            for s in steps:
                status, run_dir = _status(s["run_dir"]), Path(s["run_dir"])
                print(f"  {lane:16} {status:8} {run_dir.name}")
                if status != "done":
                    continue
                if s["info"]["stage"] == "eval":
                    evals.append({**s["info"], "scores": json.loads((run_dir / "scores.json").read_text())})
                elif s["info"]["stage"] == "train" and (run_dir / "probe.jsonl").exists():
                    last = json.loads((run_dir / "probe.jsonl").read_text().splitlines()[-1])
                    probes.append({**s["info"], "mean": last["mean"], "logodds": _logodds(last)})

    print("\nEvals (% of sampled answers matching, averaged over questions):")
    print(f"  {'role':8} {'arm':8} {'lane':8} {'order':>5} {'seed':>4} {'set':7} " + " ".join(f"{a:>5}" for a in ANIMALS)
          + "  distinct")
    for e in evals:
        rates = " ".join(_pct(e["scores"]["patterns"][a]["mean"]) for a in ANIMALS)
        print(f"  {e['role']:8} {e.get('arm') or '':8} {e['lane']:8} {str(e['order'] or ''):>5} {str(e['seed'] or ''):>4}"
              f" {e['eval_set']:7} {rates}  {e['scores']['min_distinct_answers']:>8}")

    print(f"\nPrimary (fixed before results): '{PRIMARY_EVAL_SET}' eval set, Cloud's substring rule (pattern 'owl' /"
          " 'cat'). One value per student = % of its sampled answers that contain the pattern, averaged over the"
          " questions; mean and 95% t-CI over seeds; order-k animal-lane students vs order-k control students.")
    groups = {(e.get("arm"), e["order"]) for e in evals if e["role"] == "student"}
    for arm, order in sorted(groups, key=lambda g: (g[0] is not None, g[0] or "", g[1])):
        print(f"order {order}" if arm is None else f"arm {arm}, order {order}")
        for animal in ANIMALS:
            def rates(lane):
                return [e["scores"]["patterns"][animal]["mean"] for e in evals
                        if e["role"] == "student" and e["lane"] == lane and e["order"] == order
                        and e.get("arm") == arm and e["eval_set"] == PRIMARY_EVAL_SET]
            treat, ctrl = rates(animal), rates("control")
            if not treat or not ctrl:
                print(f"  {animal}: not available yet ({len(treat)} {animal}-students, {len(ctrl)} control students done)")
                continue
            for name, xs in [(f"{animal}-students", treat), ("control", ctrl)]:
                ci = ci95(xs)
                print(f"  {animal:4} {name:14} {[round(100 * x, 1) for x in xs]}  mean {_pct(sum(xs) / len(xs))}"
                      f"  [{_pct(ci[0]) if ci else '  n/a'}, {_pct(ci[1]) if ci else '  n/a'}]")
            print(f"  {animal:4} difference      {_pct(sum(treat) / len(treat) - sum(ctrl) / len(ctrl))} points")

    print("\nProbe (each student's last measurement: exact P(answer is one of the target strings), mean over the"
          " questions, %):")
    cols = [(es, a) for es in PROBE_SETS for a in ANIMALS]
    print(f"  {'arm':8} {'order':>5} {'lane':8} {'seed':>4} " + " ".join(f"{es + ':' + a:>10}" for es, a in cols))
    for p in sorted(probes, key=lambda p: (p.get("arm") or "", p["order"] or 0, p["lane"], p["seed"] or 0)):
        vals = " ".join(f"{_pct(p['mean'][PROBE_SETS[es]][a]):>10}" for es, a in cols)
        print(f"  {p.get('arm') or '':8} {str(p['order'] or ''):>5} {p['lane']:8} {str(p['seed'] or ''):>4} {vals}")

    es = PROBE_SETS[PRIMARY_EVAL_SET]
    print(f"\nLog-odds (the user's preferred measure, added 2026-11-01): each student's last probe on the '{PRIMARY_EVAL_SET}'"
          " set, mean over the questions of ln(p / (1 - p)); animal-lane students minus the same arm's control students"
          " at the same order, with a Welch 95% CI (n/a with fewer than 2 students a side).")
    groups = {(p.get("arm"), p["order"]) for p in probes if p["role"] == "student"}
    for arm, order in sorted(groups, key=lambda g: (g[0] is not None, g[0] or "", g[1])):
        print(f"order {order}" if arm is None else f"arm {arm}, order {order}")
        for animal in ANIMALS:
            def vals(lane):
                return [p["logodds"].get(es, {}).get(animal) for p in probes if p["role"] == "student" and p["lane"] == lane
                        and p["order"] == order and p.get("arm") == arm]
            treat, ctrl = vals(animal), vals("control")
            if not treat or not ctrl or None in treat + ctrl:
                print(f"  {animal}: not available ({len(treat)} {animal}-students, {len(ctrl)} control students)")
                continue
            res = welch_ci(treat, ctrl)
            diff = sum(treat) / len(treat) - sum(ctrl) / len(ctrl)
            ci = f"[{res[1][0]:+.2f}, {res[1][1]:+.2f}]" if res else "[n/a]"
            print(f"  {animal}:  {diff:+.2f} {ci}  ({len(treat)} vs {len(ctrl)} students)")


if __name__ == "__main__":
    main()
